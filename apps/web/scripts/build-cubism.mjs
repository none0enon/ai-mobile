// Rebuild with the official Cubism SDK for Web 5-r.5 directory as the argument.
// Framework tag 5-r.5: 198a3769c26ca3d7b600e932590433badd392edd.
import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const sdk = path.resolve(process.argv[2]);
const out = fileURLToPath(new URL('../src/vendor/cubism/', import.meta.url));
const exports = {
  CubismFramework: 'live2dcubismframework',
  CubismMoc: 'model/cubismmoc',
  CubismRenderer_WebGL: 'rendering/cubismrenderer_webgl',
  CubismShaderManager_WebGL: 'rendering/cubismshader_webgl',
  CubismMatrix44: 'math/cubismmatrix44',
  CubismModelMatrix: 'math/cubismmodelmatrix',
  CubismPhysics: 'physics/cubismphysics',
  CubismPose: 'effect/cubismpose',
  CubismMotion: 'motion/cubismmotion',
  CubismMotionManager: 'motion/cubismmotionmanager',
  CubismExpressionMotion: 'motion/cubismexpressionmotion',
  CubismExpressionMotionManager: 'motion/cubismexpressionmotionmanager',
};
const shaderDir = path.join(sdk, 'Framework/Shaders/WebGL');
const shaders = Object.fromEntries(await Promise.all((await readdir(shaderDir)).filter(f => /\.(vert|frag)$/.test(f)).map(async f => [f, await readFile(path.join(shaderDir, f), 'utf8')])));
await build({
  stdin: { contents: Object.entries(exports).map(([name, file]) => `export { ${name} } from ${JSON.stringify(path.join(sdk, 'Framework/src', file))};`).join('\n'), resolveDir: sdk, loader: 'ts' },
  outfile: path.join(out, 'framework.js'), format: 'esm', target: 'es2022', bundle: true, minify: true,
  banner: { js: '/*! Live2D Cubism Web Framework 5-r.5. See Framework-LICENSE.md. Generated by scripts/build-cubism.mjs. */' },
  plugins: [{ name: 'inline-shaders', setup(b) {
    b.onLoad({ filter: /cubismshader_webgl\.ts$/ }, async ({ path: filename }) => {
      const source = await readFile(filename, 'utf8');
      const original = 'const response = await fetch(url);\n    return await response.text();';
      if (!source.includes(original)) throw new Error('SDK shader loader changed; inspect before rebuilding.');
      return { contents: source.replace(original, `return (${JSON.stringify(shaders)} as Record<string,string>)[url.split('/').pop()!]!;`), loader: 'ts' };
    });
  } }],
});
await writeFile(path.join(out, 'framework.d.ts'), '// Generated SDK boundary. The application owns its typed renderer API.\n' + Object.keys(exports).map(n => `export const ${n}: any;`).join('\n') + '\n');
